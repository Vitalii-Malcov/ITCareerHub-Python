"""
Кастомные исключения.

Идея: вместо того чтобы функции возвращали None/True/False и вызывающий
код каждый раз гадал, что это значит — репозиторий выбрасывает конкретное
исключение с понятным именем. Читается как документация:
    except UsernameAlreadyExistsError:
сразу понятно, что произошло, без комментариев.
"""


class BookstoreError(Exception):
    """Базовое исключение проекта — все остальные наследуются от него.
    Удобно, если где-то наверху нужно поймать 'любую ошибку магазина'."""


class UsernameAlreadyExistsError(BookstoreError):
    """Попытка зарегистрировать логин, который уже занят."""


class InvalidCredentialsError(BookstoreError):
    """Неверный логин или пароль при попытке входа."""
